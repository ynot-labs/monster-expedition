const dictionaries: Record<Locale, Record<MessageKey, string>> = {
  en: english,
  "zh-CN": chinese,
};

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  const translated = dictionaries[locale][key];
  if (!translated && import.meta.env.DEV) {
    console.error(`Missing ${locale} translation for ${key}`);
  }
  return (translated || english[key]).replace(/\{(\w+)\}/g, (_, token: string) =>
    values[token] === undefined ? `{${token}}` : String(values[token]),
  );
}
